print(f"\nKlasik Şampiyon: {klasik_sampiyon_ismi} (AUC = {sonuc_df.iloc[0]['AUC']:.3f})")
print(f"MLP (Derin Öğrenme) AUC = {mlp_sonuc['AUC']:.3f}")

"""## Sonuç

- 5 klasik makine öğrenmesi modeli (Lojistik Regresyon, KNN, SVM, Random Forest, XGBoost)
  eğitilip Accuracy, Precision, Recall, F1-Score ve AUC metrikleriyle karşılaştırıldı.
- Sınıf dengesizliği SMOTE ile (yalnızca eğitim setinde, veri sızıntısı olmadan) giderildi.
- En başarılı klasik model temel alınarak bir MLP (derin öğrenme) modeli kuruldu ve
  aynı metriklerle karşılaştırıldı.
- Her iki model tipi de SHAP ile açıklanabilir hale getirildi (global özellik önemi +
  tekil müşteri açıklaması).
- Streamlit prototipi için gerekli tüm nesneler (model, scaler, öznitelik sırası) diske
  kaydedildi; bir sonraki adım bu nesneleri yükleyen bir `app.py` geliştirmektir.

"""